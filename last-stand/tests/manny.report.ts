/// <reference types="node" />
import { mkdirSync, writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { BALANCE } from '../src/config/balance';
import { ENEMIES, type EnemyTypeId } from '../src/config/enemies';
import { MAPS } from '../src/config/maps';
import { TILE_SIZE } from '../src/config/map';
import { Path } from '../src/core/Path';
import { planWave } from '../src/core/waves';
import { TOWERS } from '../src/config/towers';
import { ENEMY_WEIGHT, knockback, MANNY, placements, simulate, stream, type SimOptions } from '../src/balance/manny/model';

// `npx vitest run --config vitest.balance.config.ts tests/manny.report.ts` (also part of `npm run balance`).
// Provisional Manny (docs/KNOCKBACK.md): one hero alone, no other towers, so leaks show what he stops himself.

const WAVES = [1, 5, 10];
const TYPES: [EnemyTypeId, string, number][] = [['basic', 'Goblin (light)', 20], ['runner', 'Wolf (fast)', 20], ['armored', 'Armored Orc (heavy)', 20], ['boss', 'Ogre Warlord (boss)', 3]];
const HEROES: [SimOptions['hero'], string][] = [
  [{ kind: 'manny', level: 0 }, 'Manny L1'], [{ kind: 'manny', level: 1 }, 'Manny L2'], [{ kind: 'manny', level: 2 }, 'Manny L3'],
  [{ kind: 'archer', level: 0 }, 'Archer L1'], [{ kind: 'archer', level: 2 }, 'Archer L3'],
];

it('Manny balance report', { timeout: 600_000 }, () => {
  const out: string[] = [];
  const map = MAPS.switchback;
  const path = Path.fromWaypoints(map.waypoints, map.grid);
  const spots = placements(path, map.grid.cols, map.grid.rows, TILE_SIZE);
  const routeTiles = path.length / TILE_SIZE;
  const f = (n: number, d = 1) => n.toFixed(d);

  out.push('# Manny balance report (provisional values)', '');
  out.push('Generated by `tests/manny.report.ts` from `src/balance/manny/model.ts`. Deterministic: rerunning gives the same numbers.', '');
  out.push(`Map: ${map.name}, route ${f(routeTiles)} tiles. One hero alone, no other towers. Enemies at their wave's health (×${WAVES.map((w) => f(planWave(w, BALANCE.waves).hpMultiplier, 2)).join(', ×')} for waves ${WAVES.join(', ')}) and spawn spacing; ${TYPES[0][2]} per stream (bosses: ${TYPES[3][2]}, 4 s apart).`, '');
  out.push('| Level | Punch | Interval | Targets | Launch | Knockback (light) |', '| --- | --- | --- | --- | --- | --- |');
  MANNY.levels.forEach((l, i) => out.push(`| ${i + 1} | ${l.punchDamage} | ${l.interval} s | ${l.targets} | every ${MANNY.launchEvery}rd attack, ×${MANNY.launchDamageMultiplier} damage | ${l.knockTiles} tiles, daze ${l.dazeSeconds} s |`));
  out.push('', '| Damage per second | L1 | L2 | L3 | Archer L1 | Archer L3 |', '| --- | --- | --- | --- | --- | --- |');
  const dps = MANNY.levels.map((l) => (l.punchDamage * (MANNY.launchEvery - 1 + MANNY.launchDamageMultiplier)) / (l.interval * MANNY.launchEvery));
  const arch = [TOWERS.basic.levels[0], TOWERS.basic.levels[2]].map((l) => l.damage * l.fireRate);
  out.push(`| One target | ${dps.map((d) => f(d)).join(' | ')} | ${arch.map((d) => f(d)).join(' | ')} |`);
  out.push(`| Crowd (all targets hit) | ${dps.map((d, i) => f(d * MANNY.levels[i].targets)).join(' | ')} | ${arch.map((d) => f(d)).join(' | ')} |`);
  out.push('', `Reach ${MANNY.reachTiles} tiles, wind-up ${MANNY.windupSeconds} s. Weight factors: ${Object.entries(MANNY.weightFactor).map(([k, v]) => `${k} ${v}`).join(', ')}. Repeat factors within ${MANNY.repeat.windowSeconds} s: ${MANNY.repeat.factors.join(', ')}. Airborne ${MANNY.air.base} s + ${MANNY.air.perTile} s per tile.`, '');
  out.push(`Places tested: **straight** (beside a straight stretch near mid-route, ${f(spots[0].coverageTiles)} tiles of road in reach), **corner** (most road in reach, ${f(spots[1].coverageTiles)} tiles), **spawn** (earliest reach, ${f(spots[2].progress * 100, 0)}% along).`, '');

  // 1. What one launch is worth, per weight (time lost = walk back + airborne + daze).
  out.push('## 1. One launch, by enemy (first knock)', '', '| Enemy | Speed | L1 tiles · time lost | L2 tiles · time lost | L3 tiles · time lost |', '| --- | --- | --- | --- | --- |');
  for (const [type, name] of TYPES) {
    const sp = ENEMIES[type].speedTiles;
    const cells = MANNY.levels.map((l) => { const k = knockback(l, ENEMY_WEIGHT[type], 0, 20 * TILE_SIZE, path.length, TILE_SIZE); return `${f(k.tiles, 2)} · ${f(k.tiles / sp + k.air + k.hold, 2)} s (walk ${f(k.tiles / sp, 2)} + air ${f(k.air, 2)} + daze ${f(k.hold, 2)})`; });
    out.push(`| ${name} | ${sp} tiles/s | ${cells.join(' | ')} |`);
  }
  out.push('', 'Air and daze are part of the time lost, so they are counted here; at level 1 they add about 0.3 s to a 0.75-tile knock.', '');

  // 2. Leaks per single-type stream.
  for (const spot of spots.slice(0, 2)) {
    out.push(`## 2${spot.name === 'straight' ? 'a' : 'b'}. Leaks past one hero, ${spot.name} placement`, '');
    out.push(`| Enemy | Wave | ${HEROES.map((h) => h[1]).join(' | ')} |`, `| --- | --- | ${HEROES.map(() => '---').join(' | ')} |`);
    for (const [type, name, count] of TYPES) for (const w of WAVES) {
      const plan = planWave(w, BALANCE.waves);
      const spacing = type === 'boss' ? 4 : plan.spawns[1]?.delay ?? 1;
      const cells = HEROES.map(([hero]) => { const r = simulate({ path, tileSize: TILE_SIZE, at: spot.at, hero, spawns: stream(type, count, spacing), hpMultiplier: plan.hpMultiplier }); return `${r.leaked}/${r.total}`; });
      out.push(`| ${name} | ${w} | ${cells.join(' | ')} |`);
    }
    out.push('');
  }

  // 3. Control: how much time Manny buys per enemy, and repeat knocks.
  out.push('## 3. Control value (corner placement)', '', 'Average seconds each enemy lost to Manny; most knocks and tiles lost by a single enemy; attacks that missed because the target left reach during the wind-up.', '');
  out.push('| Enemy | Wave | L1 | L2 | L3 |', '| --- | --- | --- | --- | --- |');
  for (const [type, name, count] of TYPES) for (const w of [1, 10]) {
    const plan = planWave(w, BALANCE.waves);
    const spacing = type === 'boss' ? 4 : plan.spawns[1]?.delay ?? 1;
    const cells = [0, 1, 2].map((level) => { const r = simulate({ path, tileSize: TILE_SIZE, at: spots[1].at, hero: { kind: 'manny', level }, spawns: stream(type, count, spacing), hpMultiplier: plan.hpMultiplier }); return `${f(r.avgHeld, 2)} s avg · max ${r.maxKnocksOnOne} knocks / ${f(r.maxTilesLost, 2)} tiles · ${r.whiffs} misses`; });
    out.push(`| ${name} | ${w} | ${cells.join(' | ')} |`);
  }
  out.push('');

  // 4. Real mixed waves.
  out.push('## 4. Real mixed waves (the game\'s wave plans, bosses included on wave 10)', '');
  out.push(`| Wave | Placement | ${HEROES.map((h) => h[1]).join(' | ')} |`, `| --- | --- | ${HEROES.map(() => '---').join(' | ')} |`);
  for (const w of [5, 10, 15]) for (const spot of spots.slice(0, 2)) {
    const plan = planWave(w, BALANCE.waves);
    let at = 0;
    const spawns = plan.spawns.map((s) => ({ type: s.enemy, at: (at += s.delay) }));
    const cells = HEROES.map(([hero]) => { const r = simulate({ path, tileSize: TILE_SIZE, at: spot.at, hero, spawns, hpMultiplier: plan.hpMultiplier }); return `${r.leaked}/${r.total}`; });
    out.push(`| ${w} | ${spot.name} | ${cells.join(' | ')} |`);
  }
  out.push('');

  // 4b. Sensitivity: launch every 2nd attack instead of every 3rd.
  out.push('## 4b. What if the launch charged faster? (every 2nd attack, corner placement)', '');
  out.push('| Wave | L2 every 3rd | L2 every 2nd | L3 every 3rd | L3 every 2nd |', '| --- | --- | --- | --- | --- |');
  for (const w of [5, 10, 15]) {
    const plan = planWave(w, BALANCE.waves);
    let at = 0;
    const spawns = plan.spawns.map((s) => ({ type: s.enemy, at: (at += s.delay) }));
    const cells = [[1, 3], [1, 2], [2, 3], [2, 2]].map(([level, every]) => { const r = simulate({ path, tileSize: TILE_SIZE, at: spots[1].at, hero: { kind: 'manny', level, launchEvery: every }, spawns, hpMultiplier: plan.hpMultiplier }); return `${r.leaked}/${r.total} leaked · ${f(r.avgHeld, 2)} s held avg`; });
    out.push(`| ${w} | ${cells.join(' | ')} |`);
  }
  out.push('');

  // 5. Spawn lock.
  out.push('## 5. Spawn-lock check (spawn placement, wave 15 health so enemies survive)', '', 'Longest time any single enemy spent in the first 3 tiles of the route (an unhindered goblin needs 2.0 s).', '');
  out.push('| Enemy | L1 | L2 | L3 |', '| --- | --- | --- | --- |');
  for (const [type, name, count] of TYPES) {
    const plan = planWave(15, BALANCE.waves);
    const cells = [0, 1, 2].map((level) => { const r = simulate({ path, tileSize: TILE_SIZE, at: spots[2].at, hero: { kind: 'manny', level }, spawns: stream(type, count, type === 'boss' ? 4 : 0.6), hpMultiplier: plan.hpMultiplier }); return `${f(r.spawnZoneMax, 1)} s (${r.leaked}/${r.total} leaked)`; });
    out.push(`| ${name} | ${cells.join(' | ')} |`);
  }
  const report = out.join('\n') + '\n';
  mkdirSync('docs/balance', { recursive: true });
  writeFileSync('docs/balance/manny.md', report);
  process.stdout.write(`\n${report}\n`);
});
